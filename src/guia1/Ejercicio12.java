package guia1;

/*
Mostrar los numeros del 50 al 1 usando un ciclo for.
*/

public class Ejercicio12 {
    
    public void ImprimirAlRevez () {

        System.out.println ("==========================================") ;
        System.out.println ("== Ingreso al Ejercicio 12 de la Guia 1 ==") ;
        System.out.println ("==========================================") ;

        for (int i = 50 ; i >= 1 ; i --){
            System.out.println (i) ;
        }
    }
}
